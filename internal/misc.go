package internal

import (
	"context"
	"fmt"
	"reflect"

	"google.golang.org/grpc"
	"google.golang.org/grpc/codes"
	"google.golang.org/grpc/status"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/protoadapt"
)

// CopyMessage copies data from the given in value to the given out value. It returns an
// error if the two values do not have the same type or if the given out value is not
// settable.
func CopyMessage(out, in any) error {
	pmIn, ok := in.(protoadapt.MessageV1)
	if !ok {
		return fmt.Errorf("value to copy is not a proto.Message: %T; use a custom cloner", in)
	}
	pmOut, ok := out.(protoadapt.MessageV1)
	if !ok {
		return fmt.Errorf("destination for copy is not a proto.Message: %T; use a custom cloner", in)
	}

	pmOut.Reset()
	return merge(pmOut, pmIn)
}

// merge merges src into dst. Unlike proto.Merge, it returns an error instead of
// panicking when the messages are incompatible, and it allows the two messages
// to be implemented by different Go types (for example, one generated and one
// dynamic) as long as they are the same Protobuf message.
func merge(dst, src protoadapt.MessageV1) error {
	dstV2, dstIsV2 := dst.(proto.Message)
	srcV2, srcIsV2 := src.(proto.Message)
	if dstIsV2 && srcIsV2 {
		if !dstV2.ProtoReflect().IsValid() {
			return fmt.Errorf("proto: nil destination")
		}
		if !srcV2.ProtoReflect().IsValid() {
			// merging a nil message is a no-op
			return nil
		}
		dstName := dstV2.ProtoReflect().Descriptor().FullName()
		srcName := srcV2.ProtoReflect().Descriptor().FullName()
		if dstName != srcName {
			return fmt.Errorf("proto: type mismatch: cannot copy %s to %s", srcName, dstName)
		}
		if reflect.TypeOf(dst) == reflect.TypeOf(src) {
			proto.Merge(dstV2, srcV2)
			return nil
		}
	}

	// The messages are implemented by different Go types, or at least one of
	// them predates the current Go Protobuf API. The only thing they are
	// guaranteed to share is the wire format.
	b, err := marshal(src)
	if err != nil {
		return err
	}
	return unmarshalMerge(b, dst)
}

// marshal and unmarshalMerge prefer the Marshal and Unmarshal methods of
// messages that do not implement the current API. Those are the methods that
// dynamic messages from github.com/jhump/protoreflect v1 implement, and the
// protoadapt adapters can only handle messages generated by old versions of
// protoc-gen-go, which have struct tags and no such methods.
func marshal(m protoadapt.MessageV1) ([]byte, error) {
	if m2, ok := m.(proto.Message); ok {
		return proto.Marshal(m2)
	}
	if mm, ok := m.(interface{ Marshal() ([]byte, error) }); ok {
		return mm.Marshal()
	}
	return proto.Marshal(protoadapt.MessageV2Of(m))
}

func unmarshalMerge(b []byte, m protoadapt.MessageV1) error {
	if m2, ok := m.(proto.Message); ok {
		return proto.UnmarshalOptions{Merge: true}.Unmarshal(b, m2)
	}
	if um, ok := m.(interface{ UnmarshalMerge([]byte) error }); ok {
		return um.UnmarshalMerge(b)
	}
	if um, ok := m.(interface{ Unmarshal([]byte) error }); ok {
		return um.Unmarshal(b)
	}
	return proto.UnmarshalOptions{Merge: true}.Unmarshal(b, protoadapt.MessageV2Of(m))
}

// CloneMessage returns a copy of the given value.
func CloneMessage(m any) (any, error) {
	pm, ok := m.(protoadapt.MessageV1)
	if !ok {
		return nil, fmt.Errorf("value to clone is not a proto.Message: %T; use a custom cloner", m)
	}

	// this does a proper deep copy
	return protoadapt.MessageV1Of(proto.Clone(protoadapt.MessageV2Of(pm))), nil
}

// ClearMessage resets the given value to its zero-value state. It returns an error
// if the given out value is not settable.
func ClearMessage(m any) error {
	dest := reflect.Indirect(reflect.ValueOf(m))
	if !dest.CanSet() {
		return fmt.Errorf("unable to set destination: %v", reflect.ValueOf(m).Type())
	}
	dest.Set(reflect.Zero(dest.Type()))
	return nil
}

// TranslateContextError converts the given error to a gRPC status error if it
// is a context error. If it is context.DeadlineExceeded, it is converted to an
// error with a status code of DeadlineExceeded. If it is context.Canceled, it
// is converted to an error with a status code of Canceled. If it is not a
// context error, it is returned without any conversion.
func TranslateContextError(err error) error {
	switch err {
	case context.DeadlineExceeded:
		return status.Error(codes.DeadlineExceeded, err.Error())
	case context.Canceled:
		return status.Error(codes.Canceled, err.Error())
	}
	return err
}

// FindUnaryMethod returns the method descriptor for the named method. If the
// method is not found in the given slice of descriptors, nil is returned.
func FindUnaryMethod(methodName string, methods []grpc.MethodDesc) *grpc.MethodDesc {
	for i := range methods {
		if methods[i].MethodName == methodName {
			return &methods[i]
		}
	}
	return nil
}

// FindStreamingMethod returns the stream descriptor for the named method. If
// the method is not found in the given slice of descriptors, nil is returned.
func FindStreamingMethod(methodName string, methods []grpc.StreamDesc) *grpc.StreamDesc {
	for i := range methods {
		if methods[i].StreamName == methodName {
			return &methods[i]
		}
	}
	return nil
}
